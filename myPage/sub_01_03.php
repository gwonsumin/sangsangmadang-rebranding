                <ul class="info-content">
                    수억 년의 ‘시간’ 속에 ‘우리’가 ‘여기’ 있었다.<br>

                    김소희 뮤지엄한미 연구소 학예연구관<br>

                    돌의 초상은 언제나 장대한 시간의 서사를 품고 있다. 자연은 인간이 세계를 인식하기 시작한 훨씬 이전부터 이미 거대한 시간의 구조를 몸에 새기고 있었으며, 사진은 그 묵중한 시간의
                    흔적을 기록해왔다. 그 가운데서도 돌은 자연이 만들어 낸 가장 압축적인 형태의 기록이라 할 수 있다. 방대한 자연의 역사 속에서 돌은 수억 년의 변화와 압력을 하나의 형태로 응집한
                    자연의 산물이고, 역사를 한눈에 바라볼 수 있는 시간의 단면이자, 지구의 서사를 품은 기록물이다. 별의 폭발과 원소의 순환 속에서 탄생해 지구의 지질학적 변화를 거쳐 지금 이
                    자리까지 도달한 돌은, 지구적 시간과 우주적 시간을 동시에 품은 물질적 주체라 할 수 있다. 이러한 돌의 본질은 오래전부터 사진가뿐 아니라 철학자와 신화적 상상력을 자극해 온
                    존재론적 원천이었다.<br>
                    <br>
                    현상학이 사물을 ‘보이는 그대로의 현존’ 바라보았다면, 최근의 사물 중심 철학에서는 돌을 단순한 객체가 아니라, 고유한 힘과 의미를 지닌 하나의 ‘행위적 존재’로 이해한다. 다시
                    말해 돌은 인간의 해석 이전에 이미 세계와 관계를 맺고 있으며, 그 자체로 시간과 변화를 기록해 온 주체적 물질이다. 신화적 전통 역시 돌을 영원성, 순환, 문명의 기원 등 근원적
                    의미와 결부시켜 왔다. 고대의 기념비적 구조물에서 현대의 도시 잔해에 이르기까지 돌은 인간과 세계의 경계를 가늠하는 지표로 작동하며, 수많은 층위의 의미를 사유의 대상으로 제공해
                    왔다.<br>
                    <br>
                    이와 같은 존재론적 깊이는 사진이라는 매체를 통해 더욱 풍부해진다. 사진사는 돌과 깊은 인연을 지닌다. 니엡스의 초기 사진에서 석조 건축물은 세계가 처음으로 빛의 감광을 통해
                    재현된 배경이었으며, 기술적 제약이 컸던 시대에는 움직이지 않는 석조물과 조각의 표면이 사진의 재현 가능성을 시험하는 기반이 되었다. 19세기 지질학적 기록 사진과 풍경 사진은
                    돌이라는 물질을 매개로 자연의 구조와 시간의 층위를 시각화하기도 했다. 이러한 역사 속에서 돌은 자연과 사진이 공유하는 ‘깊은 시간’의 상징으로 자리 잡았다.<br>
                    <br>
                    원정상의 네 번째 개인전, 《지층의 기억》은 바로 이러한 돌의 상징성과 시간성을 사진 매체를 통해 탐구한 연작이다. 작가는 그동안 소금과 염전을 다룬 《내 안의 우주》, 빛과 물의
                    형상에 집중한 《얼음변주곡》, 장례 의례와 바람의 이미지로 삶과 죽음의 경계를 탐색한 《염원》 등을 통해 생성과 소멸, 유한성이라는 주제를 지속적으로 확대해 왔다. 그러나 이번
                    연작에서 관심은 변화의 과정이 아니라 그 변화가 ‘남긴 자리’, 즉 물질에 퇴적된 시간의 흔적 그 자체로 이동한다. 돌의 표면을 마주하는 일이 곧 보이지 않는 시간의 두께—지질학적
                    시간, 생명의 시간, 존재의 시간—에 접촉하는 행위가 되는 것이다.<br>
                    <br>
                    《지층의 기억》은 춘천, 고성, 태백 등 강원도 일대에서 작가가 마주한 다양한 돌의 풍경을 담고 있다. 균형을 이루며 쌓인 돌탑, 끊어진 밧줄에 매인 채 자리를 잃은 돌, 절벽의
                    단면처럼 드러난 지층, 거칠게 균열을 뿜어내는 바위의 표면, 바다와 모래에 의해 부드럽게 감싸인 돌 등 자연 속에서 발견한 돌은 각기 다른 질감과 형태로 존재의 기원을 환기한다.
                    작가는 또한 개발이라는 이름 아래 파괴된 절개지와 콘크리트 잔해 속에서 드러나는 지층의 단면을 포착함으로써, 우리가 일상 속에서 무심히 지나치던 땅의 시간성과 기억을 다시금
                    불러낸다. 억겁의 시간 속에서 형성되고, 문명의 잔해 속에서도 여전히 모습을 드러내는 돌은 이처럼 과거의 죽음과 생성이 동시에 응축된 살아 있는 기록물로 다가온다.<br>
                    <br>
                    카메라는 돌의 표면에 고요히 축적된 시간에 귀 기울인다. 대형 인화로 확장된 화면 속 돌의 균열, 미세한 입자, 윤곽의 흔적들은 단순한 재현을 넘어 돌이 견뎌온 압력과 지층의
                    호흡을 시각적 감각으로 환기한다. 사진은 돌의 침묵을 해석하는 또 하나의 언어가 되며, 관객은 이미지 앞에서 자신이 가진 시간 감각과 돌이라는 물질의 심층적 시간이 겹쳐지는 독특한
                    경험을 마주한다.<br>
                    <br>
                    롤랑 바르트가 사진의 본질을 ‘그것이 존재했음(ça a été)’에 두었다는 점은 이 연작의 해석을 더욱 깊이 있게 만든다. 사진은 피사체가 실제로 존재했던 과거의 시간을 현재로
                    끌어들이는 매체이며, 서로 도달할 수 없는 두 시간의 층위가 한 장의 이미지 안에서 기묘한 중첩으로 나타난다. 《지층의 기억》 속 돌의 초상은 바로 이 지점에서 강하게 작동한다.
                    돌이 품어온 지구적·우주적 시간, 파괴와 생성의 기억, 그리고 지금 이 이미지를 바라보는 관객의 현재적 시간이 서로를 비추며 교차한다. 사진은 지층에 새겨진 시간에 잠시 귀를
                    기울이게 하는 매개자이자, 자연의 시간성을 감각적 언어로 재현하는 통로가 된다.<br>
                    <br>
                    결국 《지층의 기억》은 돌이라는 물질에 퇴적된 시간의 감각을 사진의 표면 위로 드러내는 작업이다. 이 연작은 과거와 현재, 자연과 인간, 지속과 유한성이 서로의 결을 비추며
                    사진이라는 단일한 공간에서 스쳐 지나가는 독특한 시간 미학을 만들어 낸다. 돌 앞에 선 인간은 그 속에 응축된 지구의 깊은 시간과 자신의 유한한 시간을 동시에 체감하게 되고, 바로
                    그 지점에서 우리는 오랜 시간의 층위를 견뎌온, 그리고 앞으로도 견뎌낼 돌의 모습 속에서 마주하게 되는 것이 결국 우리 자신의 존재라는 것을 깨닫게 된다. 지층의 기억을 마주한다는
                    것은 돌의 시간을 바라보는 일이자, 그 수억 년의 ‘시간’ 속에서 우리가 ‘여기’에 ‘존재 했음’을 다시 확인하는 행위이기 때문이다.
